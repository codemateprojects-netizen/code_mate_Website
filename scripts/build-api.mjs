// Bundles the Vercel function (server/vercel.ts + shared code) into a single
// dependency-free ESM file at api/inquiries.js. Run via `npm run build:api`.
import { build } from 'esbuild'

await build({
  entryPoints: ['server/vercel.ts'],
  outfile: 'api/inquiries.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-api.mjs — do not edit. Source: server/vercel.ts' },
  logLevel: 'info',
})
